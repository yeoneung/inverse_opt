"""Consistent-model versus mixed-action recovery and finite-budget diagnostics.

Closed forms use two target branches generated by one remaining latent direction.
The cell solver uses convex quadratic subproblems and feasible Lagrangian dual
witnesses. Numerical values use floating point, not validated arithmetic.
"""
import numpy as np
from .optimal_recovery import farthest_action


def two_branch_recovery(first, second):
    """Exact-arithmetic formulas for Y=[0,first] union [0,second].

    Risks are squared distances. The best single consistent prediction is on Y;
    a deterministic mixture may use its convex hull. Endpoints include radius.
    """
    original_a=np.asarray(first,float).ravel();original_b=np.asarray(second,float).ravel()
    if original_a.shape!=original_b.shape or not len(original_a):raise ValueError('Matching nonempty vectors required')
    if not np.all(np.isfinite(np.r_[original_a,original_b])):raise ValueError('Finite endpoints required')
    swapped=np.linalg.norm(original_b)>np.linalg.norm(original_a)
    a,b=(original_b,original_a) if swapped else (original_a,original_b)
    length=float(np.linalg.norm(a));short=float(np.linalg.norm(b))
    if length==0:
        return dict(mixed_center=a.copy(),mixed_risk=0.,single_center=a.copy(),single_risk=0.,
                    ratio=1.,length_ratio=0.,cosine=1.,strict_gain=False,regime='zero',
                    endpoint_weights=np.array([1.,0.,0.]),single_endpoint=1,single_fraction=0.)
    k=short/length;rho=float(np.clip(a@b/(length*short),-1.,1.)) if short else 1.
    g=k*rho;D=1+k*k-2*g
    if short==0 or rho>=k:
        center=.5*a;weights=np.array([.5,.5,0.]);mixed=length**2/4;t=.5;regime='dominated_endpoint'
    else:
        if rho<=0:
            center=.5*(a+b);weights=np.array([0.,.5,.5]);mixed=length**2*D/4;regime='nonpositive_cosine'
        else:
            gram=np.array([[1.,g],[g,k*k]])
            coefficients=np.linalg.solve(gram,np.array([.5,k*k/2]))
            center=coefficients[0]*a+coefficients[1]*b
            weights=np.r_[1-coefficients.sum(),coefficients]
            mixed=length**2*D/(4*(1-rho*rho));regime='acute_triangle'
        lower=(1-k*k)/(2*(1-g));upper=k/(2*rho) if rho>0 else np.inf
        t=float(np.clip(g,lower,upper))
    single=t*a;points=np.vstack((np.zeros_like(a),a,b))
    single_risk=float(np.max(np.sum((points-single)**2,axis=1)))
    if swapped:weights=weights[[0,2,1]]
    return dict(mixed_center=center,mixed_risk=float(mixed),single_center=single,
                single_risk=single_risk,ratio=single_risk/mixed if mixed else 1.,
                length_ratio=k,cosine=rho,strict_gain=bool(short>0 and abs(rho)<1-1e-12 and rho<k-1e-12),
                regime=regime,endpoint_weights=weights,single_endpoint=2 if swapped else 1,single_fraction=t)


def mixture_budget_bound(single_risk, mixed_risk, hoffman, target_lipschitz, budget,
                         source_error=0., target_error=0.):
    """Persistence bound with uniform source-score and target-response errors.

    The nominal zero-fit version set must remain in the perturbed budget set,
    ensured by sqrt(2*budget)>=source_error. The source cone must admit
    the supplied Hoffman bound and the target map the supplied Lipschitz
    bound; the two error inputs are uniform response-error bounds.
    """
    inputs=[single_risk,mixed_risk,hoffman,target_lipschitz,budget,source_error,target_error]
    if not np.all(np.isfinite(inputs)) or min(inputs)<0:raise ValueError('Finite nonnegative inputs required')
    if np.sqrt(2*budget)+1e-15<source_error:raise ValueError('Budget does not ensure nominal zero-fit inclusion')
    P=np.sqrt(single_risk);R=np.sqrt(mixed_risk)
    eta=target_lipschitz*hoffman*(source_error+np.sqrt(2*budget))+target_error
    lower=max(0.,P-eta-target_error);upper=R+eta
    return dict(single_radius_lower=float(lower),mixed_radius_upper=float(upper),
                radius_gap_lower=float(lower-upper),squared_gap_lower=float(lower**2-upper**2),
                target_image_tolerance=float(eta),certifies_strict_gain=bool(lower>upper))


def _restricted_cell(cells, center_cell, radius, budget, points, tolerance, max_iterations):
    import cvxpy as cp
    I=np.asarray(center_cell.information,float);A=np.asarray(center_cell.action,float)
    eigen,U=np.linalg.eigh((I+I.T)/2);eigen=np.maximum(eigen,0.)
    if budget==0:Z=U[:,eigen<=1e-11*max(1.,eigen.max())]
    else:Z=np.eye(I.shape[0])
    dimension=Z.shape[1]
    if dimension==0:
        oracle=farthest_action(cells,np.zeros(A.shape[0]),radius,budget)
        return dict(lower=oracle['value'],upper=oracle['value'],center=np.zeros(A.shape[0]),
                    parameter=np.zeros(I.shape[0]),converged=True,iterations=0,history=[])
    Q=A@Z;H=center_cell.rows@Z;J=Z.T@I@Z
    if np.linalg.norm(Q)<1e-13:
        oracle=farthest_action(cells,np.zeros(A.shape[0]),radius,budget)
        return dict(lower=oracle['value'],upper=oracle['value'],center=np.zeros(A.shape[0]),
                    parameter=np.zeros(I.shape[0]),converged=True,iterations=0,history=[])
    J=(J+J.T)/2;local_points=[np.asarray(y,float) for y in points];history=[]
    lower=0.;upper=np.inf;parameter=np.zeros(I.shape[0]);center=np.zeros(A.shape[0])
    for iteration in range(max_iterations):
        u=cp.Variable(dimension);tau=cp.Variable()
        inequalities=[cp.sum_squares(Q@u-y)<=tau for y in local_points]
        radial=cp.sum_squares(u)<=radius**2
        constraints=inequalities+[radial]
        cone=H@u>=0 if len(H) else None
        if cone is not None:constraints.append(cone)
        source=cp.quad_form(u,cp.psd_wrap(J))<=2*budget if budget>0 else None
        if source is not None:constraints.append(source)
        problem=cp.Problem(cp.Minimize(tau),constraints)
        fallback=False
        try:
            problem.solve(solver='CLARABEL',tol_gap_abs=1e-9,tol_gap_rel=1e-9,tol_feas=1e-9,max_iter=300)
        except cp.error.SolverError:
            fallback=True
            problem.solve(solver='CLARABEL',tol_gap_abs=1e-7,tol_gap_rel=1e-7,tol_feas=1e-7,max_iter=500)
        if problem.status not in ['optimal','optimal_inaccurate'] or u.value is None:
            raise RuntimeError('Restricted center subproblem: '+str(problem.status))
        parameter=Z@u.value;center=A@parameter
        weights=np.maximum([np.asarray(c.dual_value).item() for c in inequalities],0.)
        if weights.sum()==0:raise RuntimeError('No epigraph dual witness')
        weights/=weights.sum();Y=np.vstack(local_points);mean=weights@Y
        mu=np.maximum(np.asarray(cone.dual_value).ravel(),0.) if cone is not None else np.zeros(0)
        lam=max(0.,np.asarray(source.dual_value).item()) if source is not None else 0.
        rho=max(0.,np.asarray(radial.dual_value).item())+1e-8*max(1.,float(np.linalg.norm(Q,2)**2))
        matrix=Q.T@Q+lam*J+rho*np.eye(dimension)
        linear=Q.T@mean+(H.T@mu)/2
        raw_dual=float(weights@np.sum(Y**2,axis=1)-2*lam*budget-rho*radius**2-linear@np.linalg.solve(matrix,linear))
        guard=1e-7*max(1.,abs(raw_dual),float(np.max(np.sum(Y**2,axis=1))))
        dual=raw_dual-guard
        lower=max(lower,dual,0.)
        oracle=farthest_action(cells,center,radius,budget);upper=max(lower,oracle['value'])
        history.append(dict(lower=lower,upper=upper,restricted_status=problem.status,
                            solver_retry=fallback,bound_inversion=max(0.,lower-oracle['value']),
                            raw_bound_inversion=max(0.,raw_dual-oracle['value']),dual_backoff=guard))
        if upper-lower<=tolerance:break
        if iteration+1==max_iterations or min(np.linalg.norm(oracle['action']-y) for y in local_points)<1e-10:break
        local_points.append(oracle['action'])
    return dict(lower=lower,upper=upper,center=center,parameter=parameter,
                converged=upper-lower<=tolerance,iterations=len(history),history=history)


def consistent_model_recovery(cells,radius,budget,tolerance=2e-6,max_iterations=100,initial_points=None):
    """Globally compare all center cells; each restricted problem is convex.

    Candidate points supplied through initial_points must be feasible target
    images. The default uses zero only. The planar oracle supplies separation.
    """
    if not cells or radius<=0 or budget<0 or tolerance<=0 or max_iterations<1:raise ValueError('Invalid recovery inputs')
    q=cells[0].action.shape[0]
    points=[np.zeros(q)] if initial_points is None else list(np.asarray(initial_points,float))
    results=[_restricted_cell(cells,cell,radius,budget,points,tolerance,max_iterations) for cell in cells]
    best=min(results,key=lambda r:r['upper']);lower=min(r['lower'] for r in results)
    result=dict(best);result.update(lower=lower,upper=best['upper'],
        converged=best['upper']-lower<=tolerance,cell_results=results,
        total_iterations=sum(r['iterations'] for r in results))
    return result
